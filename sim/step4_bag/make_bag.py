"""Step 4a: bag model + where it sits, derived from the reference motion (runs locally, MuJoCo FK only).

    ~/HCR/third_party/.venv-gmr/bin/python sim/step4_bag/make_bag.py

Writes sim/step4_bag/assets/bag.urdf and sim/step4_bag/bag_placement.json.

Bag (bag frame: origin on the floor under the box centre, x = handle bar axis, z up):
  box 0.30 x 0.12 x 0.24 m, two handle posts (r 6 mm) at x = +-0.06 m from the box top up to a crossbar
  (r 6 mm, 0.12 m long) at z = 0.362 m. Mass is a placeholder (training randomizes it, 0.5-2.0 kg).
Placement (motion frame, i.e. the frame of bag_pickup_IMG_0531.npz; the env adds env_origin):
  handle bar centre/yaw from a search over 1485 placements that the reference hook path can thread
  (clear on the way down, seated on the lift), docs/step4_bag.md. Set-down spot = under the hook throat at the
  reference set-down. Phase frames (50 Hz): lift starts when the throat has risen 1 cm after its pickup minimum.
"""
import json
import pathlib
import sys

import mujoco
import numpy as np

REPO = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "motion" / "step2_gmr"))
from analyze_retarget import load_model  # noqa: E402

THROAT = np.array([0.060, 0.0, -0.020])          # handle seat in right_hook_link
HOOK_MOUNT = 0.13275                              # right_hook_link origin along right_elbow_yaw_link x
BOX = (0.30, 0.12, 0.24)
POST_X, BAR_R, BAR_Z = 0.06, 0.006, 0.362
YAW_OFFSET_DEG, BAR_SHIFT = 30.0, (-0.01, 0.0, 0.035)   # best candidate from the placement search


def main():
    M = np.load(REPO / "motion/step2_gmr/results/IMG_0531/robot_motion_clean.npz")
    Q = M["qpos"]
    m = load_model(); d = mujoco.MjData(m); h = m.body("right_hook_link").id
    P, Y = [], []
    for k in range(len(Q)):
        d.qpos[:] = Q[k]; mujoco.mj_kinematics(m, d); R = d.xmat[h].reshape(3, 3)
        P.append(d.xpos[h] + R @ THROAT); Y.append(R[:, 1])
    P, Y = np.array(P), np.array(Y)
    T = len(Q); half = T // 2
    k_pick = int(np.argmin(P[:half, 2])); k_place = half + int(np.argmin(P[half:, 2]))
    k_lift = k_pick + int(np.argmax(P[k_pick:, 2] > P[k_pick, 2] + 0.01))
    k_release = k_place + int(np.argmax(P[k_place:, 2] > P[k_place, 2] + 0.05))

    def horiz(v):
        v = v.copy(); v[2] = 0; return v / np.linalg.norm(v)

    yh = horiz(Y[k_pick]); a = np.radians(YAW_OFFSET_DEG)
    ax = np.array([np.cos(a) * yh[0] - np.sin(a) * yh[1], np.sin(a) * yh[0] + np.cos(a) * yh[1], 0.0])
    nrm = np.cross([0, 0, 1], ax)
    bar = P[k_pick] + BAR_SHIFT[0] * nrm + BAR_SHIFT[1] * ax + np.array([0, 0, BAR_SHIFT[2]])
    pick_yaw = float(np.arctan2(ax[1], ax[0]))
    place_ax = horiz(Y[k_place])
    place = dict(pos=[float(P[k_place, 0]), float(P[k_place, 1]), 0.0], yaw=float(np.arctan2(place_ax[1], place_ax[0])))

    out = dict(
        note="motion frame (add env origin); yaw about +z of the bag x axis (= handle bar); quaternions are built in the task",
        fps=50, frames=dict(pickup_min=k_pick, lift=k_lift, place_min=k_place, release=k_release, total=T),
        times_s={k: round(v / 50, 2) for k, v in dict(pickup_min=k_pick, lift=k_lift, place_min=k_place, release=k_release).items()},
        start=dict(pos=[float(bar[0]), float(bar[1]), 0.0], yaw=pick_yaw),
        drop=place,
        geometry=dict(box=BOX, post_x=POST_X, bar_r=BAR_R, bar_z=BAR_Z),
        hook=dict(throat_in_hook_link=THROAT.tolist(), hook_mount_x_in_forearm=HOOK_MOUNT,
                  throat_in_forearm=[HOOK_MOUNT + THROAT[0], THROAT[1], THROAT[2]]),
        reference_throat_z=dict(pickup=float(P[k_pick, 2]), place=float(P[k_place, 2])),
    )
    here = pathlib.Path(__file__).resolve().parent
    (here / "bag_placement.json").write_text(json.dumps(out, indent=2))

    bx, by, bz = BOX
    mass = 1.0
    ixx = mass / 12 * (by ** 2 + bz ** 2); iyy = mass / 12 * (bx ** 2 + bz ** 2); izz = mass / 12 * (bx ** 2 + by ** 2)
    post_len = BAR_Z - bz
    urdf = f"""<?xml version="1.0"?>
<!-- Shopping-bag stand-in for the HCR bag-transfer task. Generated by sim/step4_bag/make_bag.py -->
<robot name="bag">
  <link name="bag">
    <inertial>
      <origin xyz="0 0 {bz / 2}" rpy="0 0 0"/>
      <mass value="{mass}"/>
      <inertia ixx="{ixx:.6g}" ixy="0" ixz="0" iyy="{iyy:.6g}" iyz="0" izz="{izz:.6g}"/>
    </inertial>
    <visual><origin xyz="0 0 {bz / 2}"/><geometry><box size="{bx} {by} {bz}"/></geometry></visual>
    <collision><origin xyz="0 0 {bz / 2}"/><geometry><box size="{bx} {by} {bz}"/></geometry></collision>
    <collision><origin xyz="{-POST_X} 0 {bz + post_len / 2}"/><geometry><cylinder radius="{BAR_R}" length="{post_len}"/></geometry></collision>
    <collision><origin xyz="{POST_X} 0 {bz + post_len / 2}"/><geometry><cylinder radius="{BAR_R}" length="{post_len}"/></geometry></collision>
    <collision><origin xyz="0 0 {BAR_Z}" rpy="0 1.5707963 0"/><geometry><cylinder radius="{BAR_R}" length="{2 * POST_X + 2 * BAR_R}"/></geometry></collision>
    <visual><origin xyz="{-POST_X} 0 {bz + post_len / 2}"/><geometry><cylinder radius="{BAR_R}" length="{post_len}"/></geometry></visual>
    <visual><origin xyz="{POST_X} 0 {bz + post_len / 2}"/><geometry><cylinder radius="{BAR_R}" length="{post_len}"/></geometry></visual>
    <visual><origin xyz="0 0 {BAR_Z}" rpy="0 1.5707963 0"/><geometry><cylinder radius="{BAR_R}" length="{2 * POST_X + 2 * BAR_R}"/></geometry></visual>
  </link>
</robot>
"""
    (here / "assets").mkdir(exist_ok=True)
    (here / "assets" / "bag.urdf").write_text(urdf)
    print(json.dumps({k: out[k] for k in ("frames", "times_s", "start", "drop", "reference_throat_z")}, indent=1))


if __name__ == "__main__":
    main()
